/*
 * HSM-binding layer. The only translation unit that calls tsra_* and the only
 * one that maps tsra_status to CK_RV (tsra_pkcs11_status.h). Two builds:
 *   - TSRA_WITH_HSM: binds the native C API against a real or simulated device.
 *   - otherwise: stubs that keep the framework loadable and the object/digest
 *     paths testable with no device present.
 */

