/* tsra_status values referenced by the lazy-provision decision. Spelled out
 * here (rather than via the enum) to keep the mapping table in tsra_pkcs11_status.c the
 * single documented list. */
#define TSRA_OK 0
#define TSRA_CREDENTIALS_NOT_ESTABLISHED (-23)
#define TSRA_PARTITION_NOT_PROVISIONED (-25)
#define TSRA_PARTITION_ALREADY_PROVISIONED (-33)
#define TSRA_VAULT_APP_LIMIT_REACHED (-34)
#define TSRA_BUFFER_TOO_SMALL (-4)
#define TSRA_INTERNAL_ERROR (-5)

int32_t tsra_pkcs11_hsm_enumerate_slots(void)
{
    tsra_handle list = 0;
    tsra_status st = tsra_part_get_list(&list);
    if (st != TSRA_OK)
    {
        TSRA_PKCS11_LOG("part_get_list failed: %d", (int)st);
        return -1;
    }

    uint32_t count = 0;
    st = tsra_part_get_count(list, &count);
    if (st != TSRA_OK)
    {
        TSRA_PKCS11_LOG("part_get_count failed: %d", (int)st);
        tsra_part_free_list(list);
        return -1;
    }
    if (count > TSRA_PKCS11_MAX_SLOTS)
    {
        count = TSRA_PKCS11_MAX_SLOTS;
    }

    CK_ULONG produced = 0;
    for (uint32_t i = 0; i < count; i++)
    {
        struct tsra_part_info info;
        memset(&info, 0, sizeof(info));

        info.path.str = NULL; /* sizing pass: BUFFER_TOO_SMALL fills path.len */
        info.path.len = 0;
        st = tsra_part_get_info(list, i, &info);
        if (st != TSRA_OK && st != TSRA_BUFFER_TOO_SMALL)
        {
            TSRA_PKCS11_LOG("part_get_info(%u) sizing failed: %d", i, (int)st);
            continue;
        }
        uint32_t path_elems = info.path.len ? info.path.len : 1; /* incl. NUL */
        tsra_char *buf = (tsra_char *)calloc(path_elems, sizeof(tsra_char));
        if (buf == NULL)
        {
            continue;
        }
        info.path.str = buf;
        info.path.len = path_elems;
        st = tsra_part_get_info(list, i, &info);
        if (st != TSRA_OK)
        {
            TSRA_PKCS11_LOG("part_get_info(%u) fill failed: %d", i, (int)st);
            free(buf);
            continue;
        }

        tsra_pkcs11_slot_t *slot = &g_tsra_pkcs11.slots[produced];
        slot->present = true;
        slot->token_initialized = true; /* a discovered partition is a token */
        snprintf(slot->device_path, sizeof(slot->device_path), "%s", (const char *)buf);
        slot->api_rev_major = (uint16_t)info.api_rev_max.major;
        slot->api_rev_minor = (uint16_t)info.api_rev_max.minor;
        snprintf(slot->label, sizeof(slot->label), "TSRA partition %u", i);
        snprintf(slot->serial, sizeof(slot->serial), "TSRA%06u", i);
        free(buf);
        produced++;
    }

    tsra_part_free_list(list);
    TSRA_PKCS11_LOG("enumerated %lu TSRA partition(s)", (unsigned long)produced);
    return (int32_t)produced;
}

_Static_assert(
    (sizeof(((struct tsra_credentials *)0)->id) == P11_CREDS_ID_LEN) &&
        (sizeof(((struct tsra_credentials *)0)->pin) == P11_CREDS_PIN_LEN),
    "the configured credential matches the device's"
);

/* Build the TSRA credential from the configured partition ID and the 16-byte
 * credential PIN, or the configured default PIN when `pin` is NULL. */
static CK_RV make_creds(
    struct tsra_credentials *creds,
    const tsra_pkcs11_config *cfg,
    const CK_BYTE *pin
)
{
    memset(creds, 0, sizeof(*creds));
    if ((pin == NULL) && !cfg->default_pin_set)
    {
        return CKR_PIN_LEN_RANGE; /* the default PIN went away after C_Initialize */
    }
    memcpy(creds->id, cfg->id, sizeof(creds->id));
    memcpy(creds->pin, (pin != NULL) ? pin : cfg->default_pin, sizeof(creds->pin));
    return CKR_OK;
}

/*
 * Endorse the partition's PID public key with a caller POTA. The signature is
 * computed at runtime because the (simulated) partition key is regenerated per
 * device incarnation and cannot be precomputed: sign 0x04||x||y of the PID key
 * with ECDSA-SHA384 under a fresh P-384 key and return raw r||s (96 bytes) plus
 * that key's SPKI. Any self-consistent P-384 pair works — the device only
 * verifies the signature is consistent over the partition key, there is no
 * trust anchor to satisfy.
 *
 * Runs in a private OSSL_LIB_CTX with the default provider explicitly loaded:
 * the SDK runs its own crypto in a private libctx and leaves the process-global
 * default without a usable provider, so signing on the global context faults.
 */
static bool build_pota(
    const unsigned char *pid_spki,
    uint32_t pid_spki_len,
    unsigned char sig[96],
    unsigned char *pub,
    size_t *pub_len
)
{
    bool ok = false;
    OSSL_LIB_CTX *libctx = NULL;
    OSSL_PROVIDER *deflt = NULL;
    EVP_PKEY *sk = NULL;
    EVP_MD_CTX *md = NULL;
    unsigned char *der = NULL;
    ECDSA_SIG *es = NULL;

    /* M = the P-384 uncompressed point (0x04||x||y) = the trailing 97 bytes of
     * the SPKI DER. Sliced out rather than EVP-parsed for the libctx reason
     * above (EVP on a global-context key would fault). */
    const size_t POINT_LEN = 97;
    if (pid_spki_len < POINT_LEN)
    {
        goto cleanup;
    }
    const unsigned char *m = pid_spki + (pid_spki_len - POINT_LEN);
    if (m[0] != 0x04)
    {
        goto cleanup;
    }

    libctx = OSSL_LIB_CTX_new();
    if (libctx == NULL)
    {
        goto cleanup;
    }
    deflt = OSSL_PROVIDER_load(libctx, "default");
    if (deflt == NULL)
    {
        goto cleanup;
    }
    sk = EVP_PKEY_Q_keygen(libctx, NULL, "EC", "P-384");
    if (sk == NULL)
    {
        goto cleanup;
    }

    md = EVP_MD_CTX_new();
    if (md == NULL || EVP_DigestSignInit_ex(md, NULL, "SHA384", libctx, NULL, sk, NULL) != 1)
    {
        goto cleanup;
    }
    size_t der_len = 0;
    if (EVP_DigestSign(md, NULL, &der_len, m, POINT_LEN) != 1)
    {
        goto cleanup;
    }
    der = (unsigned char *)malloc(der_len);
    if (der == NULL || EVP_DigestSign(md, der, &der_len, m, POINT_LEN) != 1)
    {
        goto cleanup;
    }

    /* DER ECDSA sig -> raw r||s, 48 bytes each (the device requires 96). */
    const unsigned char *dp = der;
    es = d2i_ECDSA_SIG(NULL, &dp, (long)der_len);
    if (es == NULL)
    {
        goto cleanup;
    }
    const BIGNUM *r = NULL;
    const BIGNUM *s = NULL;
    ECDSA_SIG_get0(es, &r, &s);
    if (BN_bn2binpad(r, sig, 48) != 48 || BN_bn2binpad(s, sig + 48, 48) != 48)
    {
        goto cleanup;
    }

    int pl = i2d_PUBKEY(sk, NULL);
    if (pl <= 0 || (size_t)pl > *pub_len)
    {
        goto cleanup;
    }
    unsigned char *pp = pub;
    if (i2d_PUBKEY(sk, &pp) != pl)
    {
        goto cleanup;
    }
    *pub_len = (size_t)pl;
    ok = true;

cleanup:
    if (es != NULL)
    {
        ECDSA_SIG_free(es);
    }
    free(der);
    if (md != NULL)
    {
        EVP_MD_CTX_free(md);
    }
    if (sk != NULL)
    {
        EVP_PKEY_free(sk);
    }
    if (deflt != NULL)
    {
        OSSL_PROVIDER_unload(deflt);
    }
    if (libctx != NULL)
    {
        OSSL_LIB_CTX_free(libctx);
    }
    return ok;
}

/* Run the one-time provisioning ceremony on an already-open partition handle,
 * with the owner backup key `obk`. Returns the device's raw status: the
 * caller decides which non-OK statuses (e.g. a concurrent process winning the
 * provisioning race) still allow the login to proceed. */
static tsra_status provision(
    tsra_handle dev,
    const struct tsra_credentials *creds,
    CK_BYTE obk[P11_OBK_LEN]
)
{
    struct tsra_part_prop prop = { TSRA_PART_PROP_ID_PART_PUB_KEY, NULL, 0 };
    tsra_status st = tsra_part_get_prop(dev, &prop);
    if (st != TSRA_OK && st != TSRA_BUFFER_TOO_SMALL)
    {
        return st;
    }
    unsigned char *pid = (unsigned char *)malloc(prop.len ? prop.len : 1);
    if (pid == NULL)
    {
        return TSRA_INTERNAL_ERROR;
    }
    prop.val = pid;
    st = tsra_part_get_prop(dev, &prop);
    if (st != TSRA_OK)
    {
        free(pid);
        return st;
    }

    unsigned char sig[96];
    unsigned char pub[256];
    size_t pub_len = sizeof(pub);
    bool pota_ok = build_pota(pid, prop.len, sig, pub, &pub_len);
    free(pid);
    if (!pota_ok)
    {
        TSRA_PKCS11_LOG("POTA endorsement build failed");
        return TSRA_INTERNAL_ERROR;
    }

    struct tsra_buffer obk_buf = { obk, P11_OBK_LEN };
    struct tsra_owner_backup_key_config obk_cfg = { TSRA_OWNER_BACKUP_KEY_SOURCE_CALLER,
                                                    &obk_buf,
                                                    NULL };
    struct tsra_buffer sig_buf = { sig, sizeof(sig) };
    struct tsra_buffer pub_buf = { pub, (uint32_t)pub_len };
    struct tsra_pota_endorsement_data pdata = { &sig_buf, &pub_buf };
    struct tsra_pota_endorsement pota = { TSRA_POTA_ENDORSEMENT_SOURCE_CALLER, &pdata };

    return tsra_part_init(dev, creds, NULL, NULL, &obk_cfg, &pota, NULL);
}

CK_RV tsra_pkcs11_hsm_login(CK_SLOT_ID slot, const CK_BYTE *pin, uint32_t *out_session)
{
    if (out_session == NULL)
    {
        return CKR_ARGUMENTS_BAD;
    }
    if (slot >= g_tsra_pkcs11.slot_count)
    {
        return CKR_SLOT_ID_INVALID;
    }
    tsra_pkcs11_slot_t *sl = &g_tsra_pkcs11.slots[slot];

    /* Open the partition once per slot and reuse it across logins. */
    if (sl->hsm_dev == 0)
    {
        const char *path = sl->device_path;
        struct tsra_str spath = { (tsra_char *)path, (uint32_t)(strlen(path) + 1) };
        struct tsra_api_rev rev = { sl->api_rev_major ? sl->api_rev_major : 1, sl->api_rev_minor };
        tsra_handle dev = 0;
        tsra_status st = tsra_part_open(&spath, &dev, rev);
        if (st != TSRA_OK)
        {
            TSRA_PKCS11_LOG("part_open failed: %d", (int)st);
            return tsra_pkcs11_ckr_from_tsra((int)st);
        }
        sl->hsm_dev = dev;
    }

    /* All three hold secret bytes: every exit below passes the wipe at
     * cleanup. */
    struct tsra_credentials creds;
    tsra_pkcs11_config cfg;
    CK_BYTE obk[P11_OBK_LEN];
    CK_RV rv = tsra_pkcs11_config_load(&cfg);
    if (rv != CKR_OK)
    {
        TSRA_PKCS11_LOG("C_Login: configuration refused: %s", cfg.error);
        rv = CKR_FUNCTION_FAILED;
        goto cleanup;
    }
    rv = make_creds(&creds, &cfg, pin);
    if (rv != CKR_OK)
    {
        goto cleanup;
    }
    /* Read at every login, not only when provisioning, so a lost or broken key
     * file shows before the next power cycle needs it. */
    rv = tsra_pkcs11_config_obk(&cfg, obk);
    if (rv != CKR_OK)
    {
        TSRA_PKCS11_LOG("C_Login: owner backup key %s is not a regular 48-byte file", cfg.obk_path);
        goto cleanup;
    }

    /* Login = OpenSession. Provisioning is a separate, one-shot-per-power-cycle
     * device operation; run it only if the device says it is not yet provisioned
     * (cold, or after a reset). */
    tsra_handle sess = 0;
    tsra_status st = tsra_sess_open(sl->hsm_dev, &creds, NULL, &sess);
    if (st == TSRA_CREDENTIALS_NOT_ESTABLISHED || st == TSRA_PARTITION_NOT_PROVISIONED)
    {
        st = provision(sl->hsm_dev, &creds, obk);
        /* ALREADY_PROVISIONED / VAULT_APP_LIMIT_REACHED mean a concurrent
         * process won the provisioning race between our sess_open probe and the
         * part_init; the SDK treats both as "credentials already established"
         * (api/lib/src/resiliency.rs, is_credentials_already_established). The
         * sess_open retry below verifies the credential either way and its
         * result is what the caller sees. */
        if (st != TSRA_OK && st != TSRA_PARTITION_ALREADY_PROVISIONED &&
            st != TSRA_VAULT_APP_LIMIT_REACHED)
        {
            TSRA_PKCS11_LOG("provision failed: %d", (int)st);
            rv = tsra_pkcs11_ckr_from_tsra((int)st);
            goto cleanup;
        }
        st = tsra_sess_open(sl->hsm_dev, &creds, NULL, &sess);
    }
    if (st != TSRA_OK)
    {
        TSRA_PKCS11_LOG("sess_open failed: %d", (int)st);
        rv = tsra_pkcs11_ckr_from_tsra((int)st);
        goto cleanup;
    }
    *out_session = sess;
    TSRA_PKCS11_LOG("login ok (dev=%u sess=%u)", sl->hsm_dev, sess);

cleanup:
    tsra_pkcs11_wipe(&creds, sizeof(creds));
    tsra_pkcs11_wipe(obk, sizeof(obk));
    tsra_pkcs11_config_clear(&cfg);
    return rv;
}

void tsra_pkcs11_hsm_logout(uint32_t hsm_session)
{
    if (hsm_session != 0)
    {
        (void)tsra_sess_close(hsm_session);
    }
}

void tsra_pkcs11_hsm_close_all(void)
{
    for (CK_ULONG i = 0; i < g_tsra_pkcs11.slot_count; i++)
    {
        if (g_tsra_pkcs11.slots[i].hsm_dev != 0)
        {
            (void)tsra_part_close(g_tsra_pkcs11.slots[i].hsm_dev);
            g_tsra_pkcs11.slots[i].hsm_dev = 0;
        }
    }
}

