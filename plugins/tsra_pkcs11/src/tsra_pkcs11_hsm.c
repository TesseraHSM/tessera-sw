/* No device linked: one placeholder slot, and a login that "succeeds" with a
 * sentinel so the framework and object/digest paths stay exercisable. */

int32_t tsra_pkcs11_hsm_enumerate_slots(void)
{
    tsra_pkcs11_slot_t *slot = &g_tsra_pkcs11.slots[0];
    slot->present = true;
    slot->token_initialized = true;
    snprintf(slot->device_path, sizeof(slot->device_path), "tsra-placeholder-0");
    snprintf(slot->label, sizeof(slot->label), "TSRA (no device)");
    snprintf(slot->serial, sizeof(slot->serial), "TSRA000000");
    slot->api_rev_major = 1;
    slot->api_rev_minor = 0;
    return 1; /* slot count: the placeholder above */
}

CK_RV tsra_pkcs11_hsm_login(CK_SLOT_ID slot, const CK_BYTE *pin, uint32_t *out_session)
{
    (void)slot;
    (void)pin;
    if (out_session == NULL)
    {
        return CKR_ARGUMENTS_BAD;
    }
    *out_session = 0xFFFFFFFFu; /* sentinel: logged in, no device session */
    return CKR_OK;
}

void tsra_pkcs11_hsm_logout(uint32_t hsm_session)
{
    (void)hsm_session;
}

void tsra_pkcs11_hsm_close_all(void)
{
}

