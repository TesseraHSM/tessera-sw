"""
Generate the known-answer vector arrays integration-tests/cpp/vectors/*.inc
from the vectors in the tsra_crypto crate (crates/crypto/src/testvectors):
NIST CAVP, plus the BoringSSL RSA-OAEP set. The output is committed; run this
by hand after a source or filter change and commit the result:

    python3 tools/gen_vectors.py

Only vectors the module and the host oracle can take are kept, and of those
a few per key, hash or curve; each file's header says what was kept. Byte
strings stay hex; vectors::hex() decodes them.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
PLUGIN = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(PLUGIN))
OUT = os.path.join(PLUGIN, "integration-tests", "cpp", "vectors")
TSRA = os.path.join(REPO, "crates", "crypto", "src", "testvectors")

# tsra_crypto hash names to the OpenSSL names the host oracle takes.
MD = {"TestHashAlgo::Sha1": "SHA1", "TestHashAlgo::Sha256": "SHA256",
      "TestHashAlgo::Sha384": "SHA384", "TestHashAlgo::Sha512": "SHA512"}
MD_LEN = {"SHA1": 20, "SHA256": 32, "SHA384": 48, "SHA512": 64}


def hexbytes(rust):
    return bytes(int(b, 16) for b in rust.split(",") if b.strip()).hex()


def tsra_vectors(fname, kind):
    """The fields of each `kind` struct literal in a tsra_crypto vector file:
    byte arrays (inline or a named constant) as hex, other values as text."""
    text = open(os.path.join(TSRA, fname)).read()
    consts = {k: hexbytes(v) for k, v in re.findall(r"const (\w+): &\[u8\] = &\[([^\]]*)\]", text)}
    out = []
    for block in text.split(kind + " {")[1:]:
        fields = {k: hexbytes(v) for k, v in re.findall(r"(\w+): &\[([^\]]*)\]", block)}
        for k, v in re.findall(r"(\w+): ([\w:]+),", block):
            fields.setdefault(k, consts.get(v, v))
        out.append(fields)
    return out


def first(vecs, n, group):
    """The first n vectors of each group, in file order."""
    seen = {}
    out = []
    for v in vecs:
        g = group(v)
        seen[g] = seen.get(g, 0) + 1
        if seen[g] <= n:
            out.append(v)
    return out


def der(b, i=0):
    """The value of the DER element at b[i], and the index after it."""
    n = b[i + 1]
    i += 2
    if n & 0x80:
        n, i = int.from_bytes(b[i:i + (n & 0x7F)], "big"), i + (n & 0x7F)
    return b[i:i + n], i + n


def rsa_public(pkcs8):
    """The modulus and public exponent of a PKCS#8 RSA key, as CKA_MODULUS and
    CKA_PUBLIC_EXPONENT carry them (big-endian, no leading zero)."""
    info, _ = der(bytes.fromhex(pkcs8))
    _, i = der(info)  # version
    _, i = der(info, i)  # privateKeyAlgorithm
    key, _ = der(info, i)
    rsa, _ = der(key)
    _, i = der(rsa)  # version
    n, i = der(rsa, i)
    e, _ = der(rsa, i)
    return n.lstrip(b"\0").hex(), e.lstrip(b"\0").hex()


def emit(fname, header, body):
    path = os.path.join(OUT, fname)
    with open(path, "w") as f:
        f.write("// Copyright (c) Microsoft Corporation.\n// Licensed under the MIT License.\n\n")
        f.write("// clang-format off\n// GENERATED by tools/gen_vectors.py, do not edit by hand.\n")
        f.write("\n".join(header) + "\n\n")
        f.write('#pragma once\n\n#include "vectors/vectors.hpp"\n\n')
        f.write("namespace vectors\n{\n\n" + "\n".join(body) + "\n\n} // namespace vectors\n")
    print(f"{path}: {os.path.getsize(path)} bytes")


def q(s):
    return f'"{s}"'


def array(ctype, name, rows):
    return [f"inline constexpr {ctype} {name}[] = {{"] + [f"    {{ {r} }}," for r in rows] + ["};"]


def aes_cbc_nist():
    rows, srcs = [], []
    for bits in (128, 192, 256):
        for kind in ("gf_sbox", "mmt"):
            fname = f"cbc_{bits}_nist_{kind}_test_vectors.rs"
            srcs.append(fname)
            for v in tsra_vectors("aes/" + fname, "AesCbcTestVector"):
                rows.append(", ".join(q(v[k]) for k in ("key", "iv", "plaintext", "ciphertext")))
    header = ["// Source: NIST CAVP AESAVS GFSbox and MMT (CBC), as carried by the tsra_crypto",
              "// crate in crates/crypto/src/testvectors/aes/:"]
    header += [f"//   {s}" for s in srcs]
    header.append(f"// Kept: all {len(rows)} vectors (AES-128, AES-192, AES-256).")
    emit("aes_cbc_nist.inc", header, array("AesVector", "kAesCbcNist", rows))


def aes_xts_nist():
    fname = "xts_256_nist_test_vectors.rs"
    groups = {}
    for v in tsra_vectors("aes/" + fname, "AesXtsTestVector"):
        groups.setdefault((v["encrypt"], len(v["plaintext"])), []).append(v)
    rows = []
    for key in sorted(groups):
        for v in groups[key][:5]:
            # tsra_crypto carries the data unit sequence number as 8 bytes;
            # the PKCS#11 tweak is the same number as 16 little-endian bytes.
            tweak = v["tweak"].ljust(32, "0")
            rows.append(", ".join(q(x) for x in (v["key"], tweak, v["plaintext"], v["ciphertext"])))
    header = ["// Source: NIST CAVP XTSVS XTSGenAES256.rsp, as carried by the tsra_crypto crate",
              f"// in crates/crypto/src/testvectors/aes/{fname}.",
              f"// Kept: the first 5 vectors of each direction and data unit length ({len(rows)}",
              "// in all). The tweak is the 16-byte little-endian data unit number."]
    emit("aes_xts_nist.inc", header, array("AesVector", "kAesXtsNist", rows))


def fixed(h, n):
    """The hex h as exactly n digits; NIST pads the P-521 values to 68 bytes."""
    assert int(h[:-n] or "0", 16) == 0, h
    return h[-n:]


def ecdh_nist():
    rows, srcs = [], []
    for curve in ("p256", "p384", "p521"):
        fname = f"ecdh_{curve}_test_vectors.rs"
        srcs.append(fname)
        for v in tsra_vectors("ecc/" + fname, "EcdhNistTestVector")[:5]:
            n = len(v["ziut"])
            x, y, d = (fixed(v[k], n) for k in ("_qcavs_x", "_qcavs_y", "_diut"))
            rows.append(", ".join(q(s) for s in (f"P-{curve[1:]}", "04" + x + y, d, v["ziut"])))
    header = ["// Source: NIST CAVP KAS ECC CDH primitive (KAS_ECC_CDH_PrimitiveTest.txt), as",
              "// carried by the tsra_crypto crate in crates/crypto/src/testvectors/ecc/:"]
    header += [f"//   {s}" for s in srcs]
    header.append(f"// Kept: the first 5 vectors of each curve ({len(rows)} in all).")
    emit("ecdh_nist.inc", header, array("EcdhVector", "kEcdhNist", rows))


def rsa_bits(v):
    return len(rsa_public(v["der"])[0]) * 4


def rsa_rows(vecs, prefix, cols):
    """An RsaKey constant per distinct key, and a row per vector: the hash, the
    key and the hex fields in cols."""
    keys, body, rows = {}, [], []
    for v in vecs:
        key = v["der"]
        if key not in keys:
            keys[key] = f"{prefix}{len(keys)}"
            n, e = rsa_public(key)
            body.append(f"inline constexpr RsaKey {keys[key]} = {{ {q(key)}, {q(n)}, {q(e)} }};")
        rows.append(f"{q(MD[v['hash_algo']])}, &{keys[key]}, " + ", ".join(q(v[c]) for c in cols))
    return body + [""], rows


def rsa_kept(vecs):
    sizes = sorted({rsa_bits(v) for v in vecs})
    mds = sorted({MD[v["hash_algo"]] for v in vecs}, key=MD_LEN.get)
    return (", ".join(f"RSA-{b}" for b in sizes) + " with " + ", ".join(mds) +
            f" ({len(vecs)} vectors)")


def rsa_vectors(fname, kind, der_field):
    vecs = tsra_vectors("rsa/" + fname, kind)
    for v in vecs:
        v["der"] = v[der_field]
    return vecs


def rsa_sig_vectors(fname, kind, der_field):
    # Both files pair one 2048-bit signature with the 3072-bit key (index 29,
    # which the crate's own tests skip): keep modulus-sized signatures only.
    return [v for v in rsa_vectors(fname, kind, der_field)
            if len(v["s"]) == len(rsa_public(v["der"])[0])]


def rsa_pkcs1_nist():
    fname = "rsa_pkcs1_test_vectors.rs"
    vecs = first(rsa_sig_vectors(fname, "PkcsTestVector", "priv_der"), 2,
                 lambda v: (v["der"], v["hash_algo"]))
    body, rows = rsa_rows(vecs, "kRsaPkcs1Key", ("msg", "s"))
    header = ["// Source: NIST CAVP RSA PKCS#1 v1.5 signatures, as carried by the tsra_crypto",
              f"// crate in crates/crypto/src/testvectors/rsa/{fname}.",
              "// Kept: the first 2 vectors of each key and hash:",
              f"// {rsa_kept(vecs)}."]
    emit("rsa_pkcs1_nist.inc", header, body + array("RsaSigVector", "kRsaPkcs1Nist", rows))


def rsa_pss_nist():
    fname = "rsa_pss_test_vectors.rs"
    vecs = [v for v in rsa_sig_vectors(fname, "PssTestVector", "private_der")
            if int(v["salt_len"]) == MD_LEN[MD[v["hash_algo"]]]]
    vecs = first(vecs, 2, lambda v: (v["der"], v["hash_algo"]))
    body, rows = rsa_rows(vecs, "kRsaPssKey", ("msg", "s"))
    header = ["// Source: NIST CAVP RSA-PSS signatures, as carried by the tsra_crypto crate",
              f"// in crates/crypto/src/testvectors/rsa/{fname}.",
              "// Kept: the vectors with MGF1 and a salt as long as the hash, the PSS form the",
              "// host oracle takes, and of those the first 2 of each key and hash:",
              f"// {rsa_kept(vecs)}."]
    emit("rsa_pss_nist.inc", header, body + array("RsaSigVector", "kRsaPssNist", rows))


def rsa_oaep():
    fname = "rsa_oaep_test_vectors.rs"
    vecs = [v for v in rsa_vectors(fname, "OaepTestVector", "priv_der") if rsa_bits(v) >= 2048]
    assert all(v["label"] == "None" for v in vecs)
    body, rows = rsa_rows(vecs, "kRsaOaepKey", ("plaintext", "ciphertext"))
    header = ["// Source: the BoringSSL RSA-OAEP vectors (crypto/evp/evp_tests.txt), as carried",
              f"// by the tsra_crypto crate in crates/crypto/src/testvectors/rsa/{fname}.",
              "// Kept: the keys of 2048 bits or more, the sizes the SDK takes, all with MGF1",
              f"// and the OAEP hash and no label: {rsa_kept(vecs)}."]
    emit("rsa_oaep.inc", header, body + array("RsaOaepVector", "kRsaOaep", rows))


def main():
    aes_cbc_nist()
    aes_xts_nist()
    ecdh_nist()
    rsa_pkcs1_nist()
    rsa_pss_nist()
    rsa_oaep()


if __name__ == "__main__":
    main()
