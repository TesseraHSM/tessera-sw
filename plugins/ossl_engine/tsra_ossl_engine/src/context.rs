/// Length of a credential id or PIN (`HsmCredentials`), and of its hex form.
const CREDENTIALS_SIZE: usize = 16;
const CREDENTIALS_HEX_SIZE: usize = CREDENTIALS_SIZE * 2;

const ENV_CREDENTIALS_ID: &str = "TSRA_CREDENTIALS_ID";
const ENV_CREDENTIALS_PIN: &str = "TSRA_CREDENTIALS_PIN";

/// Per-engine state stored in `ENGINE` ex_data.
pub struct EngineData {
    /// HSM private keys loaded via the engine's `load_private_key` path (and
    /// generated by keygen), each backing one or more engine-bound `EC_KEY`s
    /// that stash a non-owning pointer to it in their ex_data.
    ///
    /// Owned here — never via an `EC_KEY` ex_data free callback, which would
    /// leave a libcrypto-held function pointer into this `.so` (see the module
    /// docs of [`tsra_ossl_engine_core::exdata`]). HSM keys are not deleted by
    /// their own drop: a key is deleted explicitly when the last `EC_KEY` using
    /// it is freed (the engine's `EC_KEY_METHOD` `finish`, see
    /// [`crate::keyload`]), and any still retained are deleted by this type's
    /// `Drop` at engine teardown.
    loaded_keys: RetainedKeys<HsmEccPrivateKey>,
    /// Loaded HSM RSA private keys, retained like `loaded_keys` (released by the
    /// engine's `RSA_METHOD` `finish`, see [`crate::rsaload`]).
    loaded_rsa_keys: RetainedKeys<HsmRsaPrivateKey>,
    /// The HSM's RSA unwrapping key pair, fetched once on first import and
    /// cached for the engine's lifetime (fetching is a stateful HSM op, so
    /// re-fetching would leak handles). Deleted at teardown, mirroring the
    /// provider's session-scoped unwrapping-key cache.
    unwrapping_key: Mutex<Option<UnwrappingKey>>,
    hsm: Mutex<Option<HsmEngineContext>>,
}

/// The HSM's RSA unwrapping key pair: the public half wraps an external key
/// (`tsra.input_key`), the private half unwraps it into the HSM.
pub(crate) struct UnwrappingKey {
    pub(crate) private: HsmRsaPrivateKey,
    pub(crate) public: HsmRsaPublicKey,
}

impl Default for EngineData {
    fn default() -> Self {
        Self::new()
    }
}

impl EngineData {
    pub fn new() -> Self {
        Self {
            loaded_keys: RetainedKeys::new(),
            loaded_rsa_keys: RetainedKeys::new(),
            unwrapping_key: Mutex::new(None),
            hsm: Mutex::new(None),
        }
    }

    /// True once an `HsmEngineContext` has been installed via `open_hsm_*`.
    pub fn is_hsm_open(&self) -> bool {
        self.hsm.lock().is_some()
    }

    /// Open the HSM using `settings` (already parsed) and `creds`.
    /// Idempotent: subsequent calls return `Ok(())` without re-opening.
    ///
    /// The lock is held across `HsmEngineContext::open` so concurrent first-use
    /// callers serialize on the open instead of racing two sessions open
    /// and discarding one.
    pub fn open_hsm_with(
        &self,
        settings: ResiliencySettings,
        creds: HsmCredentials,
    ) -> EngineResult<()> {
        let mut guard = self.hsm.lock();
        if guard.is_some() {
            return Ok(());
        }
        *guard = Some(HsmEngineContext::open(settings, creds)?);
        Ok(())
    }

    /// Open the HSM by reading settings + credentials from the process
    /// environment.
    ///
    /// Idempotent: if the HSM is already open (e.g. opened earlier via
    /// [`open_hsm_with`]) this returns `Ok` without touching the environment,
    /// so a caller like the key loader can invoke it unconditionally.
    pub fn open_hsm_from_env(&self) -> EngineResult<()> {
        if self.is_hsm_open() {
            return Ok(());
        }
        let settings = ResiliencySettings::from_env()
            .map_err(|e| EngineError::wrap("resiliency settings", e))?;
        let creds = credentials_from_env()?;
        self.open_hsm_with(settings, creds)
    }

    /// Run `f` with the open HSM session. The lock is held across `f`, so key
    /// operations serialize with each other and with the open. Errors if the
    /// HSM has not been opened.
    ///
    /// Crate-internal: it hands out a raw `HsmSession`, so it is used only by
    /// the key loader (and tests), not exposed as public engine API.
    pub(crate) fn with_session<F, R>(&self, f: F) -> EngineResult<R>
    where
        F: FnOnce(&HsmSession) -> EngineResult<R>,
    {
        let guard = self.hsm.lock();
        let ctx = guard
            .as_ref()
            .ok_or_else(|| EngineError::Other("HSM session not open".into()))?;
        f(&ctx.session)
    }

    /// Take ownership of a loaded HSM private key on behalf of the `EC_KEY`
    /// `owner` it is about to be attached to, and return a stable non-owning
    /// pointer to it for stashing in that `EC_KEY`'s ex_data. The pointer stays
    /// valid until its last owner is dropped via
    /// [`release_loaded_key`](Self::release_loaded_key) (which deletes the key
    /// from the HSM — HSM keys are not deleted by their own drop), or until
    /// this `EngineData` is dropped.
    ///
    /// Ownership is tracked by owner address rather than read back from
    /// ex_data, because `EC_KEY_copy` overwrites a destination's ex_data
    /// without telling us what it held.
    ///
    /// Crate-internal: an implementation detail of the key loader.
    pub(crate) fn retain_loaded_key(
        &self,
        key: HsmEccPrivateKey,
        owner: *const ffi::EC_KEY,
    ) -> *const HsmEccPrivateKey {
        self.loaded_keys.retain(key, owner.addr())
    }

    /// Make the `EC_KEY` `owner` (an `EC_KEY_copy` destination) own exactly
    /// `ptr`, or nothing if `ptr` is null: whatever it owned before is
    /// released first, deleting that key from the HSM if no other `EC_KEY`
    /// uses it. Returns false if `ptr` is non-null but isn't retained.
    pub(crate) fn rebind_loaded_key(
        &self,
        owner: *const ffi::EC_KEY,
        ptr: *const HsmEccPrivateKey,
    ) -> bool {
        let (shared, displaced) = self.loaded_keys.rebind(owner.addr(), ptr);
        if let Some(key) = displaced {
            delete_hsm_key(key, "replaced EC private key");
        }
        shared
    }

    /// Drop `owner`'s reference on the key it was given by
    /// [`retain_loaded_key`](Self::retain_loaded_key) or
    /// [`rebind_loaded_key`](Self::rebind_loaded_key), deleting the key from
    /// the HSM when its last owner goes. Called when an `EC_KEY` using the key
    /// is finished, and to roll back a partial load. A no-op if `owner` holds
    /// no key.
    pub(crate) fn release_loaded_key(&self, owner: *const ffi::EC_KEY) {
        if let Some(key) = self.loaded_keys.release(owner.addr()) {
            delete_hsm_key(key, "released EC private key");
        }
    }

    /// RSA counterpart of [`retain_loaded_key`](Self::retain_loaded_key): take
    /// ownership of a loaded HSM RSA private key on behalf of `owner` and
    /// return a stable non-owning pointer for stashing in `RSA` ex_data.
    pub(crate) fn retain_loaded_rsa_key(
        &self,
        key: HsmRsaPrivateKey,
        owner: *const ffi::RSA,
    ) -> *const HsmRsaPrivateKey {
        self.loaded_rsa_keys.retain(key, owner.addr())
    }

    /// RSA counterpart of [`release_loaded_key`](Self::release_loaded_key).
    pub(crate) fn release_loaded_rsa_key(&self, owner: *const ffi::RSA) {
        if let Some(key) = self.loaded_rsa_keys.release(owner.addr()) {
            delete_hsm_key(key, "released RSA private key");
        }
    }

    /// Run `f` with the HSM's RSA unwrapping key pair, fetching and caching it
    /// on first use. `session` must be this engine's open session (the caller
    /// already holds it via [`with_session`](Self::with_session)).
    pub(crate) fn with_unwrapping_key<F, R>(&self, session: &HsmSession, f: F) -> EngineResult<R>
    where
        F: FnOnce(&HsmRsaPrivateKey, &HsmRsaPublicKey) -> EngineResult<R>,
    {
        let mut guard = self.unwrapping_key.lock();
        if guard.is_none() {
            *guard = Some(fetch_unwrapping_key(session)?);
        }
        let uk = guard
            .as_ref()
            .ok_or_else(|| EngineError::Other("unwrapping key unavailable".into()))?;
        f(&uk.private, &uk.public)
    }
}

impl Drop for EngineData {
    /// HSM keys are not deleted by their own drop: delete every still-retained
    /// key and the cached unwrapping key explicitly at engine teardown.
    fn drop(&mut self) {
        for key in self.loaded_keys.drain() {
            delete_hsm_key(key, "retained EC private key");
        }
        for key in self.loaded_rsa_keys.drain() {
            delete_hsm_key(key, "retained RSA private key");
        }
        if let Some(uk) = self.unwrapping_key.get_mut().take() {
            // The public half's delete is a documented no-op; deleting the
            // private half releases the HSM handle.
            delete_hsm_key(uk.private, "RSA unwrapping key");
        }
    }
}

/// HSM keys backing engine-bound OpenSSL key objects, each with the addresses
/// of the objects that own it. An object owns at most one key.
struct RetainedKeys<K> {
    // `Box` gives each key a stable heap address: the loaders stash a raw
    // pointer to it in ex_data, which must stay valid across `Vec` growth.
    keys: Mutex<Vec<(Box<K>, Vec<usize>)>>,
}

impl<K> RetainedKeys<K> {
    fn new() -> Self {
        Self {
            keys: Mutex::new(Vec::new()),
        }
    }

    /// Store `key` owned by `owner` and return its stable address.
    fn retain(&self, key: K, owner: usize) -> *const K {
        let boxed = Box::new(key);
        let ptr: *const K = boxed.as_ref();
        self.keys.lock().push((boxed, vec![owner]));
        ptr
    }

    /// Move `owner` from whatever key it owns to `ptr` (or to nothing if
    /// `ptr` is null). Returns whether `owner` now owns `ptr`, and the key it
    /// previously owned if that lost its last owner (for the caller to delete
    /// outside the lock).
    fn rebind(&self, owner: usize, ptr: *const K) -> (bool, Option<K>) {
        let mut keys = self.keys.lock();
        let displaced = Self::take_owner(&mut keys, owner);
        if ptr.is_null() {
            return (true, displaced);
        }
        match keys.iter_mut().find(|(k, _)| std::ptr::eq(k.as_ref(), ptr)) {
            Some((_, owners)) => {
                owners.push(owner);
                (true, displaced)
            }
            None => (false, displaced),
        }
    }

    /// Drop `owner`'s reference, returning its key once the last owner goes
    /// (for the caller to delete outside the lock).
    fn release(&self, owner: usize) -> Option<K> {
        Self::take_owner(&mut self.keys.lock(), owner)
    }

    fn take_owner(keys: &mut Vec<(Box<K>, Vec<usize>)>, owner: usize) -> Option<K> {
        let pos = keys
            .iter()
            .position(|(_, owners)| owners.contains(&owner))?;
        let owners = &mut keys[pos].1;
        owners.retain(|o| *o != owner);
        if !owners.is_empty() {
            return None;
        }
        Some(*keys.remove(pos).0)
    }

    /// Remove every key regardless of owners (engine teardown).
    fn drain(&mut self) -> impl Iterator<Item = K> + '_ {
        self.keys.get_mut().drain(..).map(|(k, _)| *k)
    }
}

/// Size of the HSM's RSA unwrapping key pair, which the HSM fixes.
pub(crate) const RSA_UNWRAPPING_KEY_BITS: u32 = 2048;

/// Fetch the HSM's RSA unwrapping key pair (unwrap/wrap usage), the props
/// matching the api's `HsmRsaKeyUnwrappingKeyGenAlgo` requirements.
fn fetch_unwrapping_key(session: &HsmSession) -> EngineResult<UnwrappingKey> {
    let priv_props = HsmKeyPropsBuilder::default()
        .class(HsmKeyClass::Private)
        .key_kind(HsmKeyKind::Rsa)
        .bits(RSA_UNWRAPPING_KEY_BITS)
        .can_unwrap(true)
        .build()
        .map_err(|e| EngineError::wrap("build unwrapping private props", e))?;
    let pub_props = HsmKeyPropsBuilder::default()
        .class(HsmKeyClass::Public)
        .key_kind(HsmKeyKind::Rsa)
        .bits(RSA_UNWRAPPING_KEY_BITS)
        .can_wrap(true)
        .build()
        .map_err(|e| EngineError::wrap("build unwrapping public props", e))?;
    let mut algo = HsmRsaKeyUnwrappingKeyGenAlgo::default();
    let (private, public) =
        HsmKeyManager::generate_key_pair(session, &mut algo, priv_props, pub_props)
            .map_err(|e| EngineError::wrap("fetch RSA unwrapping key", e))?;
    Ok(UnwrappingKey { private, public })
}

/// Best-effort HSM key deletion for cleanup paths: failures are logged, never
/// propagated (the caller's operation should not fail over cleanup).
pub(crate) fn delete_hsm_key<K: HsmKeyDeleteOp>(key: K, what: &str) {
    if let Err(e) = key.delete_key() {
        tracing::warn!(target: "tsra", "failed to delete {what} from the HSM: {e}");
    }
}

/// Live HSM partition + session.
///
/// Both fields are RAII holders: dropping them closes the session and
/// releases the partition. They are held (not currently read) to keep the
/// session open for the lifetime of the `EngineData`.
struct HsmEngineContext {
    #[allow(dead_code)]
    partition: HsmPartition,
    #[allow(dead_code)]
    session: HsmSession,
}

impl HsmEngineContext {
    fn open(settings: ResiliencySettings, creds: HsmCredentials) -> EngineResult<Self> {
        let info = HsmPartitionManager::partition_info_list()
            .into_iter()
            .next()
            .ok_or_else(|| EngineError::Other("no HSM partitions found".into()))?;

        let api_rev_range = info
            .api_rev_range
            .ok_or_else(|| EngineError::Other(format!("partition {} has no API rev", info.path)))?;
        let api_rev = api_rev_range.max();

        let partition = HsmPartitionManager::open_partition(&info.path, api_rev)
            .map_err(|e| EngineError::wrap(format!("open_partition({})", info.path), e))?;

        // With resiliency off the SDK wants a clean partition. reset() is a
        // no-op on a freshly opened one and does NOT clear BK3 (one-shot per
        // power cycle) — the warm-device case is handled by the OBK→MOBK
        // fallback below.
        if !settings.enabled {
            partition
                .reset()
                .map_err(|e| EngineError::wrap("partition reset", e))?;
        }

        // Mirror the provider (tsra_ossl_hsm.c): always attempt init with
        // the plaintext OBK first. On a cold device `init_bk3` runs and
        // derives a fresh MOBK; on a warm device the SDK returns
        // Bk3AlreadyInitialized and we retry with the MOBK a previous init
        // persisted.
        let caller_obk = matches!(settings.obk_source, HsmOwnerBackupKeySource::Caller);
        let pota = build_pota_endorsement(&partition, &settings)?;
        let first = partition.init(
            creds,
            None,
            None,
            build_obk_config(&settings)?,
            pota.clone(),
            build_resiliency_config(&settings)?,
        );

        match first {
            Ok(()) => {}
            Err(HsmError::Bk3AlreadyInitialized) if caller_obk => {
                reinit_with_cached_mobk(&partition, creds, &settings, pota)?;
            }
            Err(e) => return Err(EngineError::wrap("partition init", e)),
        }

        // Persist the device's MOBK so a later warm re-init can recover
        // (mirrors the provider). `mobk_vec()` is populated only when this
        // init actually derived the MOBK — the cold-device `init_bk3` path.
        // On a warm re-init the SDK reports credentials already established
        // and returns no MOBK; the file persisted by the original cold init
        // is still valid, so there is nothing new to write. Caller source
        // only; TPM re-derives the MOBK each init.
        if caller_obk {
            let mobk = Zeroizing::new(partition.mobk_vec());
            if !mobk.is_empty() {
                persist_secret_file(&settings.mobk_path, mobk.as_slice()).map_err(|e| {
                    EngineError::wrap(
                        format!("persist MOBK to '{}'", settings.mobk_path.display()),
                        e,
                    )
                })?;
            }
        }

        let session = partition
            .open_session(api_rev, &creds, None)
            .map_err(|e| EngineError::wrap("open_session", e))?;

        Ok(Self { partition, session })
    }
}

/// Warm-device re-init: the plaintext OBK was rejected with
/// `Bk3AlreadyInitialized`, so re-init from the MOBK a previous cold init
/// persisted at `settings.mobk_path`. Caller-OBK source only.
fn reinit_with_cached_mobk(
    partition: &HsmPartition,
    creds: HsmCredentials,
    settings: &ResiliencySettings,
    pota: HsmPotaEndorsement,
) -> EngineResult<()> {
    let mobk = Zeroizing::new(
        FileMobkCallback::new(settings.mobk_path.clone())
            .get_mobk()
            .map_err(|e| {
                EngineError::wrap(
                    format!(
                        "device reports BK3 already initialized but cached MOBK \
                         '{}' is unusable — restore it or reset/power-cycle the \
                         device",
                        settings.mobk_path.display()
                    ),
                    e,
                )
            })?,
    );
    let obk_config = HsmOwnerBackupKeyConfig::new(
        HsmOwnerBackupKeySource::Caller,
        HsmOwnerBackupKey::from_masked_key(mobk.as_slice()),
    );
    partition
        .init(
            creds,
            None,
            None,
            obk_config,
            pota,
            build_resiliency_config(settings)?,
        )
        .map_err(|e| EngineError::wrap("partition init (MOBK retry)", e))
}

/// Persist key material to `path` durably: write a `0600` temp file, flush it,
/// then atomically rename into place, so a torn write can't leave a corrupt
/// MOBK that would break a later warm re-init.
fn persist_secret_file(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    use std::io::Write;
    use std::os::unix::fs::OpenOptionsExt;
    use std::sync::atomic::AtomicU64;
    use std::sync::atomic::Ordering;

    // PID plus a per-call counter, so two engines in one process writing the
    // same target path can't collide on the temp name.
    static SEQ: AtomicU64 = AtomicU64::new(0);
    let seq = SEQ.fetch_add(1, Ordering::Relaxed);
    let mut tmp_name = path
        .file_name()
        .ok_or_else(|| std::io::Error::new(std::io::ErrorKind::InvalidInput, "no file name"))?
        .to_os_string();
    tmp_name.push(format!(".tmp.{}.{seq}", std::process::id()));
    let tmp = path.with_file_name(tmp_name);

    // Exclusive-create (O_EXCL via create_new): if a file already exists at
    // this temp name — a crash leftover or a planted file in a shared dir —
    // fail instead of truncating it, so secret material is never written into
    // a file we did not just create with 0600.
    let mut f = std::fs::OpenOptions::new()
        .create_new(true)
        .write(true)
        .mode(SECRET_FILE_MODE)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(&tmp)?;

    // We own `tmp` now, so on any later failure remove it (and only it) so a
    // partial copy of key material is not left behind.
    if let Err(e) = (|| -> std::io::Result<()> {
        f.write_all(bytes)?;
        f.sync_all()?;
        std::fs::rename(&tmp, path)
    })() {
        let _ = std::fs::remove_file(&tmp);
        return Err(e);
    }

    // fsync the directory so the rename itself survives a crash.
    if let Some(dir) = path.parent().filter(|d| !d.as_os_str().is_empty()) {
        if let Ok(d) = std::fs::File::open(dir) {
            let _ = d.sync_all();
        }
    }
    Ok(())
}

/// Assemble the resiliency config for one `partition.init` attempt.
///
/// `HsmResiliencyConfig` is consumed by `init` and holds non-`Clone` callback
/// boxes, so each attempt rebuilds it from a `settings` clone.
fn build_resiliency_config(
    settings: &ResiliencySettings,
) -> EngineResult<Option<tsra_api::HsmResiliencyConfig>> {
    settings
        .clone()
        .into_resiliency_config()
        .map_err(|e| EngineError::wrap("resiliency config", e))
}

/// Build the initial POTA endorsement OpenSSL hands to `partition.init`.
/// When source is `Caller` we use [`FilePotaCallback`] to sign the
/// partition's PID public key; when source is `Tpm` we pass `None`.
fn build_pota_endorsement(
    partition: &HsmPartition,
    settings: &ResiliencySettings,
) -> EngineResult<HsmPotaEndorsement> {
    match settings.pota_source {
        HsmPotaEndorsementSource::Caller => {
            let priv_path = settings.pota_priv_path.clone().ok_or_else(|| {
                EngineError::Other("TSRA_POTA_PRIVATE_KEY_PATH is required for caller POTA".into())
            })?;
            let pub_path = settings.pota_pub_path.clone().ok_or_else(|| {
                EngineError::Other("TSRA_POTA_PUBLIC_KEY_PATH is required for caller POTA".into())
            })?;
            let pid_pub = partition
                .pub_key()
                .map_err(|e| EngineError::wrap("partition pub_key", e))?;
            let cb = FilePotaCallback::new(priv_path, pub_path);
            let data = cb
                .endorse(&[], &pid_pub, &[])
                .map_err(|e| EngineError::wrap("POTA endorse", e))?;
            let endorsement = HsmPotaEndorsementData::new(data.signature(), data.pub_key());
            Ok(HsmPotaEndorsement::new(
                HsmPotaEndorsementSource::Caller,
                Some(endorsement),
            ))
        }
        _ => Ok(HsmPotaEndorsement::new(settings.pota_source, None)),
    }
}

/// Build the OBK config for the *first* `partition.init` attempt: Caller
/// source supplies the plaintext OBK (which runs `init_bk3`); Tpm supplies an
/// empty key. The warm-device MOBK retry is handled in [`HsmEngineContext::open`].
fn build_obk_config(settings: &ResiliencySettings) -> EngineResult<HsmOwnerBackupKeyConfig> {
    match settings.obk_source {
        HsmOwnerBackupKeySource::Caller => {
            // Plaintext OBK (BK3); our copy is scrubbed on drop.
            let cb = FileMobkCallback::new(settings.obk_path.clone());
            let obk = Zeroizing::new(
                cb.get_mobk()
                    .map_err(|e| EngineError::wrap("OBK load", e))?,
            );
            Ok(HsmOwnerBackupKeyConfig::new(
                HsmOwnerBackupKeySource::Caller,
                HsmOwnerBackupKey::from_obk(obk.as_slice()),
            ))
        }
        _ => Ok(HsmOwnerBackupKeyConfig::new(
            settings.obk_source,
            HsmOwnerBackupKey::default(),
        )),
    }
}

fn credentials_from_env() -> EngineResult<HsmCredentials> {
    let mut id = cred_field(ENV_CREDENTIALS_ID)?;
    let mut pin = cred_field(ENV_CREDENTIALS_PIN)?;
    let creds = HsmCredentials::new(&id, &pin);
    // Scrub our decoded copies; HsmCredentials holds its own.
    id.zeroize();
    pin.zeroize();
    Ok(creds)
}

/// Read a credential from `var` (hex). There is no default: a missing
/// credential is a hard error.
fn cred_field(var: &'static str) -> EngineResult<[u8; CREDENTIALS_SIZE]> {
    match std::env::var(var) {
        Ok(s) => {
            // The source hex string holds the secret; scrub it on drop.
            let s = Zeroizing::new(s);
            decode_credential_hex(&s, var)
        }
        Err(std::env::VarError::NotPresent) => Err(EngineError::Other(format!(
            "{var} must be set ({CREDENTIALS_HEX_SIZE} hex chars)"
        ))),
        Err(std::env::VarError::NotUnicode(_)) => {
            Err(EngineError::Other(format!("{var} is not valid UTF-8")))
        }
    }
}

fn decode_credential_hex(s: &str, var: &'static str) -> EngineResult<[u8; CREDENTIALS_SIZE]> {
    if s.len() != CREDENTIALS_HEX_SIZE {
        return Err(EngineError::Other(format!(
            "{var} must be {CREDENTIALS_HEX_SIZE} hex chars ({CREDENTIALS_SIZE} bytes), got {}",
            s.len()
        )));
    }
    let mut out = [0u8; CREDENTIALS_SIZE];
    for (dst, pair) in out.iter_mut().zip(s.as_bytes().chunks_exact(2)) {
        let pair_str = std::str::from_utf8(pair)
            .map_err(|_| EngineError::Other(format!("{var} has non-ASCII byte")))?;
        *dst = u8::from_str_radix(pair_str, 16)
            .map_err(|_| EngineError::Other(format!("{var} has non-hex byte")))?;
    }
    Ok(out)
}

