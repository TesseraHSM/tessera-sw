/// Hybrid KEM label.
const LABEL: &[u8] = b"MLKEM1024-P384";

/// Traditional component curve.
const CURVE: HsmEccCurve = HsmEccCurve::P384;

/// P-384 scalar / coordinate / shared-secret length.
const COORD: usize = 48;

/// SEC1 uncompressed P-384 point length (`Nelem`).
const ELEM: usize = 1 + 2 * COORD;

/// Hybrid seed length (`Nsk`).
const SEED_LEN: usize = 32;

/// Hybrid public key / encapsulated key length (`Npk = Nenc`).
const NENC: usize = mlkem::CT_LEN + ELEM;

/// Expanded seed length: ML-KEM `d ‖ z` followed by the P-384 scalar seed.
const SEED_FULL_LEN: usize = MLKEM_SEED_LEN + COORD;

const SEED_FULL_ALGO: HsmHashAlgo = match NonZeroU16::new(SEED_FULL_LEN as u16) {
    Some(n) => HsmHashAlgo::Shake256(n),
    None => panic!("zero SHAKE output"),
};

// Combiner input layout: ss_PQ ‖ ss_T ‖ ct_T ‖ ek_T ‖ label.
const SS_T_OFF: usize = MLKEM_SHARED_SECRET_LEN;
const CT_T_OFF: usize = SS_T_OFF + COORD;
const EK_T_OFF: usize = CT_T_OFF + ELEM;
const LABEL_OFF: usize = EK_T_OFF + ELEM;
const COMBINER_LEN: usize = LABEL_OFF + LABEL.len();

/// P-384 group order `n`, big-endian.
const P384_ORDER: [u8; COORD] = [
    0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
    0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xc7, 0x63, 0x4d, 0x81, 0xf4, 0x37, 0x2d, 0xdf,
    0x58, 0x1a, 0x0d, 0xb2, 0x48, 0xb0, 0xa7, 0x7a, 0xec, 0xec, 0x19, 0x6a, 0xcc, 0xc5, 0x29, 0x73,
];

/// `RandomScalar` acceptance test: `0 < OS2IP(k) < n`, in constant
/// time since `k` is the private scalar.
fn scalar_in_range(k: &[u8]) -> bool {
    if k.len() != COORD {
        return false;
    }
    let mut borrow = 0i16;
    let mut any = 0u8;
    for (&a, &b) in k.iter().zip(P384_ORDER.iter()).rev() {
        let d = i16::from(a) - i16::from(b) - borrow;
        borrow = (d >> 8) & 1;
        any |= a;
    }
    (borrow == 1) & (any != 0)
}

/// Rejects platforms whose PAL ECC scalar / coordinate encoding is not
/// the plain 48-byte P-384 form assumed by the buffers here.
fn check_curve_layout<P: HsmCrypto>() -> HsmResult<()> {
    if CURVE.wire_coord_len(P::BYTE_ORDER) != COORD {
        return Err(HsmError::InvalidArg);
    }
    Ok(())
}

/// Hybrid Encap.
///
/// # Parameters
///
/// * `pk_r` — `ek_PQ ‖ SEC1(ek_T)` ([`NENC`] bytes).
/// * `enc` — output `ct_PQ ‖ ct_T` (at least [`NENC`] bytes).
/// * `shared_secret` — output (32 bytes).
pub(super) async fn encap<'a, P>(
    pal: &P,
    io: &P::Io,
    pk_r: &[u8],
    enc: &mut [u8],
    shared_secret: &mut HsmDmaBuf,
    alloc: &'a impl HsmScopedAlloc,
) -> HsmResult<()>
where
    P: HsmCrypto + HsmAlloc + 'a,
{
    check_curve_layout::<P>()?;
    if pk_r.len() != NENC || enc.len() < NENC {
        return Err(HsmError::InvalidArg);
    }
    let (ek_pq, ek_t) = pk_r.split_at(mlkem::EK_LEN);
    let (ct_pq_out, rest) = enc.split_at_mut(mlkem::CT_LEN);
    let ct_t_out = &mut rest[..ELEM];

    let ek_t_op = alloc_bytes(2 * COORD, alloc)?;
    sec1_to_operand(P::BYTE_ORDER, ek_t, ek_t_op, COORD)?;

    let comb = alloc_bytes(COMBINER_LEN, alloc)?;
    let (ss_pq, rest) = comb.split_at_mut(SS_T_OFF);
    let (ss_t, rest) = rest.split_at_mut(COORD);
    let (ct_t, rest) = rest.split_at_mut(ELEM);
    let (ek_t_dst, label) = rest.split_at_mut(ELEM);

    mlkem::encaps(pal, io, ek_pq, ct_pq_out, ss_pq, alloc).await?;

    // Ephemeral P-384 key pair (query, then generate).
    let (priv_size, pub_size) = pal
        .ecc_gen_keypair(io, alloc, CURVE, None, HsmEccPct::KeyAgreement)
        .await?;
    if pub_size != 2 * COORD {
        return Err(HsmError::InvalidArg);
    }
    let eph = alloc_bytes(priv_size + pub_size, alloc)?;
    let (sk_e, pk_e) = eph.split_at_mut(priv_size);
    let (sk_len, pk_len) = pal
        .ecc_gen_keypair(
            io,
            alloc,
            CURVE,
            Some((&mut *sk_e, &mut *pk_e)),
            HsmEccPct::KeyAgreement,
        )
        .await?;
    if pk_len != 2 * COORD {
        return Err(HsmError::InvalidArg);
    }

    pal.ecdh_derive(io, CURVE, &sk_e[..sk_len], ek_t_op, ss_t)
        .await?;
    byte_order::int_to_be(P::BYTE_ORDER, ss_t);
    operand_to_sec1(P::BYTE_ORDER, &pk_e[..pk_len], ct_t, COORD)?;
    ct_t_out.copy_from_slice(ct_t);
    ek_t_dst.copy_from_slice(ek_t);
    label.copy_from_slice(LABEL);

    pal.hash(
        io,
        HsmHashAlgo::Sha3_256,
        comb,
        shared_secret,
        HsmDigestForm::Standard,
    )
    .await
}

/// Hybrid Decap.
///
/// # Parameters
///
/// * `enc` — `ct_PQ ‖ SEC1(ct_T)` ([`NENC`] bytes).
/// * `sk_r` — the 32-byte hybrid seed.
/// * `shared_secret` — output (32 bytes).
///
/// # Returns
///
/// * `Err(HsmError::InvalidArg)` — malformed lengths, `ct_T` not a
///   valid P-384 point, or the seed yields an out-of-range P-384
///   scalar.
pub(super) async fn decap<'a, P>(
    pal: &P,
    io: &P::Io,
    enc: &[u8],
    sk_r: &[u8],
    shared_secret: &mut HsmDmaBuf,
    alloc: &'a impl HsmScopedAlloc,
) -> HsmResult<()>
where
    P: HsmCrypto + HsmAlloc + 'a,
{
    check_curve_layout::<P>()?;
    if enc.len() != NENC || sk_r.len() != SEED_LEN {
        return Err(HsmError::InvalidArg);
    }
    let (ct_pq, ct_t_in) = enc.split_at(mlkem::CT_LEN);

    // expandDecapsKey: seed_full = SHAKE256(seed, 112).
    let seed = dma_copy_in(alloc, sk_r)?;
    let seed_full = alloc_bytes(SEED_FULL_LEN, alloc)?;
    pal.hash(io, SEED_FULL_ALGO, seed, seed_full, HsmDigestForm::Standard)
        .await?;
    let (seed_pq, seed_t) = seed_full.split_at_mut(MLKEM_SEED_LEN);
    if !scalar_in_range(seed_t) {
        return Err(HsmError::InvalidArg);
    }
    let dk_t = alloc_bytes(COORD, alloc)?;
    byte_order::int_copy_from_be(P::BYTE_ORDER, dk_t, seed_t)?;

    let comb = alloc_bytes(COMBINER_LEN, alloc)?;
    let (ss_pq, rest) = comb.split_at_mut(SS_T_OFF);
    let (ss_t, rest) = rest.split_at_mut(COORD);
    let (ct_t, rest) = rest.split_at_mut(ELEM);
    let (ek_t, label) = rest.split_at_mut(ELEM);

    mlkem::decaps(pal, io, seed_pq, ct_pq, ss_pq, alloc).await?;

    let ct_t_op = alloc_bytes(2 * COORD, alloc)?;
    sec1_to_operand(P::BYTE_ORDER, ct_t_in, ct_t_op, COORD)?;
    pal.ecdh_derive(io, CURVE, dk_t, ct_t_op, ss_t).await?;
    byte_order::int_to_be(P::BYTE_ORDER, ss_t);

    let ek_t_op = alloc_bytes(2 * COORD, alloc)?;
    pal.ecc_pub_from_priv(io, CURVE, dk_t, ek_t_op).await?;
    operand_to_sec1(P::BYTE_ORDER, ek_t_op, ek_t, COORD)?;
    ct_t.copy_from_slice(ct_t_in);
    label.copy_from_slice(LABEL);

    pal.hash(
        io,
        HsmHashAlgo::Sha3_256,
        comb,
        shared_secret,
        HsmDigestForm::Standard,
    )
    .await
}
