//! `memcpy` and `memset`, and the AEABI entry points the compiler calls for
//! them, small enough for the 32 KB ITCM.
//!
//! `compiler_builtins` supplies all of these as weak symbols, meant to be
//! replaced. Its versions handle every alignment with unrolled shift-and-
//! merge loops and come to 540 bytes; these come to about 100. Everything
//! large this image copies or clears is word aligned -- request
//! workspaces, sponge states, operand-slot regions -- and takes a word (two
//! words, clearing) a store here, falling back to bytes only when a pointer
//! is not aligned. Clearing is also faster than `compiler_builtins`', which
//! stores a word behind a compare and two branches; the big workspaces go
//! through `pqc_ml::fast_zero`, eight words a store, regardless.

core::arch::global_asm!(
    ".syntax unified",
    ".thumb",
    ".section .text.tsra_mem,\"ax\",%progbits",
    // void *memcpy(void *d, const void *s, size_t n), and the AEABI forms,
    // which take the same arguments and need not return d.
    ".global memcpy",
    ".global __aeabi_memcpy",
    ".global __aeabi_memcpy4",
    ".global __aeabi_memcpy8",
    ".type memcpy, %function",
    ".type __aeabi_memcpy, %function",
    ".type __aeabi_memcpy4, %function",
    ".type __aeabi_memcpy8, %function",
    ".thumb_func",
    "memcpy:",
    ".thumb_func",
    "__aeabi_memcpy:",
    ".thumb_func",
    "__aeabi_memcpy4:",
    ".thumb_func",
    "__aeabi_memcpy8:",
    "    mov     r12, r0",
    "    orr     r3, r0, r1",
    "    lsls    r3, r3, #30",
    "    bne     2f",
    "1:  subs    r2, r2, #4",
    "    bcc     3f",
    "    ldr     r3, [r1], #4",
    "    str     r3, [r0], #4",
    "    b       1b",
    "3:  adds    r2, r2, #4",
    "2:  cbz     r2, 4f",
    "5:  ldrb    r3, [r1], #1",
    "    strb    r3, [r0], #1",
    "    subs    r2, r2, #1",
    "    bne     5b",
    "4:  mov     r0, r12",
    "    bx      lr",
    // void *memset(void *d, int c, size_t n); the AEABI forms take (d, n,
    // c), and the memclr ones (d, n) with c = 0.
    ".global memset",
    ".global __aeabi_memset",
    ".global __aeabi_memset4",
    ".global __aeabi_memset8",
    ".global __aeabi_memclr",
    ".global __aeabi_memclr4",
    ".global __aeabi_memclr8",
    ".type memset, %function",
    ".type __aeabi_memset, %function",
    ".type __aeabi_memset4, %function",
    ".type __aeabi_memset8, %function",
    ".type __aeabi_memclr, %function",
    ".type __aeabi_memclr4, %function",
    ".type __aeabi_memclr8, %function",
    ".thumb_func",
    "__aeabi_memclr:",
    ".thumb_func",
    "__aeabi_memclr4:",
    ".thumb_func",
    "__aeabi_memclr8:",
    "    movs    r2, #0",
    ".thumb_func",
    "__aeabi_memset:",
    ".thumb_func",
    "__aeabi_memset4:",
    ".thumb_func",
    "__aeabi_memset8:",
    "    mov     r3, r1",
    "    mov     r1, r2",
    "    b       6f",
    ".thumb_func",
    "memset:",
    "    mov     r3, r2",
    "6:  and     r1, r1, #0xFF",
    "    orr     r1, r1, r1, lsl #8",
    "    orr     r1, r1, r1, lsl #16",
    "    mov     r2, r1",
    "    mov     r12, r0",
    "    tst     r0, #3",
    "    bne     2f",
    "1:  subs    r3, r3, #8",
    "    bcc     3f",
    "    strd    r1, r2, [r0], #8",
    "    b       1b",
    "3:  adds    r3, r3, #8",
    "2:  cbz     r3, 4f",
    "5:  strb    r1, [r0], #1",
    "    subs    r3, r3, #1",
    "    bne     5b",
    "4:  mov     r0, r12",
    "    bx      lr",
);
