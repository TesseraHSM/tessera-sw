1:
    ldm     r1!, {r3, r4, r5, r6, r7}
    ubfx    r8, r3, #0, #18
    rsb     r8, r8, #0x20000
    lsr     r9, r3, #18
    bfi     r9, r4, #14, #4
    rsb     r9, r9, #0x20000
    ubfx    r10, r4, #4, #18
    rsb     r10, r10, #0x20000
    lsr     r11, r4, #22
    bfi     r11, r5, #10, #8
    rsb     r11, r11, #0x20000
    stm     r0!, {r8, r9, r10, r11}
    ubfx    r8, r5, #8, #18
    rsb     r8, r8, #0x20000
    lsr     r9, r5, #26
    bfi     r9, r6, #6, #12
    rsb     r9, r9, #0x20000
    ubfx    r10, r6, #12, #18
    rsb     r10, r10, #0x20000
    lsr     r11, r6, #30
    bfi     r11, r7, #2, #16
    rsb     r11, r11, #0x20000
    stm     r0!, {r8, r9, r10, r11}
    mov     r12, r7
    ldm     r1!, {r3, r4, r5, r6}
    lsr     r8, r12, #16
    bfi     r8, r3, #16, #2
    rsb     r8, r8, #0x20000
    ubfx    r9, r3, #2, #18
