@ ML-DSA BitUnpack of y and z: 256 fields of d bits, little-endian as
@ FIPS 204 packs them, each read back as gamma1 - field.
@
@ void pqc_ml_dsa_unpack_z20(int32_t a[256], const uint8_t buf[640])
@     gamma1 = 2^19, d = 20: eight coefficients a five-word group.
@ void pqc_ml_dsa_unpack_z18(int32_t a[256], const uint8_t buf[576])
@     gamma1 = 2^17, d = 18: sixteen coefficients a nine-word group.
@
@ buf must be word aligned. A field inside one word is a ubfx; one that
@ straddles two is a shift and a bfi; four coefficients go out per stm.
@ Generated by a script from the field layout; see FIPS 204 BitUnpack.

.syntax unified
.thumb
.text

.global pqc_ml_dsa_unpack_z20
.type pqc_ml_dsa_unpack_z20, %function
.align 2
pqc_ml_dsa_unpack_z20:
    push    {r4-r11, lr}
    mov     lr, #32
1:
    ldm     r1!, {r3, r4, r5, r6, r7}
    ubfx    r8, r3, #0, #20
    rsb     r8, r8, #0x80000
    lsr     r9, r3, #20
    bfi     r9, r4, #12, #8
    rsb     r9, r9, #0x80000
    ubfx    r10, r4, #8, #20
    rsb     r10, r10, #0x80000
    lsr     r11, r4, #28
    bfi     r11, r5, #4, #16
    rsb     r11, r11, #0x80000
    stm     r0!, {r8, r9, r10, r11}
    lsr     r8, r5, #16
    bfi     r8, r6, #16, #4
    rsb     r8, r8, #0x80000
    ubfx    r9, r6, #4, #20
    rsb     r9, r9, #0x80000
    lsr     r10, r6, #24
    bfi     r10, r7, #8, #12
    rsb     r10, r10, #0x80000
    lsr     r11, r7, #12
    rsb     r11, r11, #0x80000
    stm     r0!, {r8, r9, r10, r11}
    subs    lr, lr, #1
    bne     1b
    pop     {r4-r11, pc}
.size pqc_ml_dsa_unpack_z20, .-pqc_ml_dsa_unpack_z20

