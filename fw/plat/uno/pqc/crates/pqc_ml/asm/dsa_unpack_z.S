    lsr     r8, r4, #24
    bfi     r8, r5, #8, #10
    rsb     r8, r8, #0x20000
    ubfx    r9, r5, #10, #18
    rsb     r9, r9, #0x20000
    lsr     r10, r5, #28
    bfi     r10, r6, #4, #14
    rsb     r10, r10, #0x20000
    lsr     r11, r6, #14
    rsb     r11, r11, #0x20000
